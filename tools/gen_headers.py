#!/usr/bin/env python3
"""Make gfopenntlm.library's fd, clib, inline and library entry files from
include/sfd/gfopenntlm_lib.sfd. MIT, Copyright (c) 2026 AmiCradle Team.
Run from the top of the tree: python3 tools/gen_headers.py [--check]"""
import os, re, sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SFD = os.path.join(HERE, "include/sfd/gfopenntlm_lib.sfd")
BANNER = "Generated by tools/gen_headers.py from include/sfd/gfopenntlm_lib.sfd: do not edit. MIT, (c) 2026 AmiCradle Team."
LINE = re.compile(r"^(.+?)\s*\b(\w+)\((.*)\)\s*\(([^)]*)\)\s*$")

def parse():
    meta, funcs, bias = {}, [], None
    for raw in open(SFD):
        s = raw.rstrip("\n")
        if not s or s.startswith("*"):
            continue
        if s.startswith("=="):
            k, _, v = s[2:].partition(" ")
            meta[k] = v.strip()
            if k == "bias":
                bias = int(v)
            continue
        m = LINE.match(s)
        if not m:
            sys.exit("bad sfd line: " + s)
        ret, name, args, regs = m.group(1).strip(), m.group(2), m.group(3).strip(), m.group(4).strip()
        alist = []
        if args:
            for a in args.split(","):
                a = a.strip()
                am = re.match(r"^(.*?)(\w+)$", a)
                alist.append((am.group(1).strip(), am.group(2)))
        rlist = [r.strip() for r in regs.split(",")] if regs else []
        if len(rlist) != len(alist):
            sys.exit("registers do not match arguments: " + name)
        funcs.append((ret, name, alist, rlist, bias))
        bias += 6
    return meta, funcs

def fd(meta, funcs):
    o = ["* " + BANNER, "##base " + meta["base"], "##bias " + str(funcs[0][4]), "##public"]
    for ret, name, a, r, b in funcs:
        o.append("%s(%s)(%s)" % (name, ",".join(n for _, n in a), "/".join(r)))
    o.append("##end")
    return "\n".join(o) + "\n"

def proto(ret, name, a):
    return "%s %s(%s)" % (ret, name, ", ".join("%s %s" % (t, n) if not t.endswith("*") else "%s%s" % (t, n) for t, n in a) or "VOID")

def clib(meta, funcs):
    o = ["/* " + BANNER + " */", "#ifndef CLIB_GFOPENNTLM_PROTOS_H", "#define CLIB_GFOPENNTLM_PROTOS_H", "",
         "#include <libraries/gfopenntlm.h>", "", "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    for ret, name, a, r, b in funcs:
        o.append(proto(ret, name, a) + ";")
    o += ["", "#ifdef __cplusplus", "}", "#endif", "", "#endif", ""]
    return "\n".join(o)

def inline(meta, funcs):
    o = ["/* " + BANNER + " */", "#ifndef INLINE_GFOPENNTLM_H", "#define INLINE_GFOPENNTLM_H", "",
         "#ifndef __INLINE_MACROS_H", "#include <inline/macros.h>", "#endif", "",
         "#ifndef GFOPENNTLM_BASE_NAME", "#define GFOPENNTLM_BASE_NAME GFOpenNTLMBase", "#endif", ""]
    for ret, name, a, r, b in funcs:
        nr = ret == "VOID"
        mac = "LP%d%s" % (len(a), "NR" if nr else "")
        parts = ["0x%x" % b] + ([] if nr else [ret]) + [name]
        for (t, n), reg in zip(a, r):
            parts += [t, n, reg]
        parts += ["", "GFOPENNTLM_BASE_NAME"]
        o.append("#define %s(%s) \\" % (name, ", ".join(n for _, n in a)))
        o.append("\t%s(%s)" % (mac, ", ".join(parts)))
        o.append("")
    o += ["#endif", ""]
    return "\n".join(o)

def entries(meta, funcs):
    o = ["/* " + BANNER + " */",
         "/* the library's entry points: registers in, the C calls of src/gn_api.c out. */"]
    for ret, name, a, r, b in funcs:
        args = ", ".join("REG(%s, %s)" % (reg, ("%s %s" % (t, n)) if not t.endswith("*") else t + n) for (t, n), reg in zip(a, r))
        args = (args + ", " if args else "") + "REG(a6, struct Library *base)"
        call = "%s(%s)" % (name, ", ".join(n for _, n in a))
        body = ("%s;" % call) if ret == "VOID" else ("return %s;" % call)
        o.append("static %s LIB_%s(%s)" % (ret, name, args))
        o.append("{ (void)base; %s }" % body)
    return "\n".join(o) + "\n"

def vectors(meta, funcs):
    o = ["/* " + BANNER + " */", "/* the vectors after the four standard ones, in LVO order. */"]
    for f in funcs:
        o.append("    (APTR)LIB_%s," % f[1])
    return "\n".join(o) + "\n"

def main():
    meta, funcs = parse()
    out = {
        "include/fd/gfopenntlm_lib.fd": fd(meta, funcs),
        "include/clib/gfopenntlm_protos.h": clib(meta, funcs),
        "include/inline/gfopenntlm.h": inline(meta, funcs),
        "library/gn_entries.h": entries(meta, funcs),
        "library/gn_vectors.h": vectors(meta, funcs),
    }
    check = "--check" in sys.argv
    bad = 0
    for rel, text in out.items():
        p = os.path.join(HERE, rel)
        if check:
            if not os.path.exists(p) or open(p).read() != text:
                print("out of date: " + rel); bad = 1
        else:
            os.makedirs(os.path.dirname(p), exist_ok=True)
            open(p, "w").write(text)
    sys.exit(bad)

if __name__ == "__main__":
    main()
